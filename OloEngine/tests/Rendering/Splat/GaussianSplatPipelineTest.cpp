    TEST(GaussianSplatPacking, ColourAndOpacitySurviveWithinOneQuantisationStep)
    {
        // One 8-bit step, not half a step: round-to-nearest lands exactly on
        // the half-step boundary for any value that is an odd multiple of
        // 1/510 (0.5 is the first), so a half-step bound is not attainable.
        constexpr f32 kStep = 1.0f / 255.0f;
        for (f32 v = 0.0f; v <= 1.0f; v += 1.0f / 32.0f)
        {
            const glm::vec4 back = UnpackColorOpacity(PackColorOpacity(glm::vec3(v, 1.0f - v, 0.25f), v));
            EXPECT_NEAR(back.r, v, kStep);
            EXPECT_NEAR(back.g, 1.0f - v, kStep);
            EXPECT_NEAR(back.a, v, kStep);
        }
    }

    TEST(GaussianSplatPacking, HalfCovarianceDegradesPredictablyForSmallSplats)
    {
        // The record stores the six covariance terms as HALVES, and a
        // covariance term is a squared length. Half's smallest normal is
        // 6.1e-5, so every splat whose sigma is below about 7.8 mm has its
        // covariance stored as a DENORMAL, where the spacing is a flat
        // 5.96e-8 and precision stops scaling with the value.
        //
        // That is survivable and it is not free, so the size of the effect is
        // measured here rather than asserted in prose. Error is reported on
        // SIGMA (a length, which is what a viewer sees as a splat's size), not
        // on the covariance term, so it is half the relative error of the
        // stored quantity.
        struct Case
        {
            f32 Sigma;
            f32 ToleranceOnSigma;
        };
        // 10 m down to 1 mm: the range a metre-scale scan actually occupies.
        // 0.25 mm is included to pin where the packing gives up.
        for (const Case testCase : { Case{ 10.0f, 0.005f }, Case{ 1.0f, 0.005f }, Case{ 0.1f, 0.005f },
                                     Case{ 0.01f, 0.005f }, Case{ 0.001f, 0.02f }, Case{ 0.00025f, 0.25f } })
        {
            const std::array<f32, 6> cov = CovarianceFromScaleRotation(glm::log(glm::vec3(testCase.Sigma)),
                                                                       glm::vec4(1.0f, 0.0f, 0.0f, 0.0f));
            u32 a = 0;
            u32 b = 0;
            u32 c = 0;
            PackCovariance(cov, a, b, c);
            const std::array<f32, 6> back = UnpackCovariance(a, b, c);

            ASSERT_TRUE(std::isfinite(back[0])) << "sigma = " << testCase.Sigma;
            ASSERT_TRUE(std::isfinite(ConservativeSigma(GpuSplat{ glm::vec3(0.0f), 0u, a, b, c, 0u })))
                << "sigma = " << testCase.Sigma;
            ASSERT_GT(back[0], 0.0f) << "sigma = " << testCase.Sigma << " underflowed to zero";
            const f32 recovered = std::sqrt(back[0]);
            const f32 relative = std::abs(recovered - testCase.Sigma) / testCase.Sigma;
            EXPECT_LE(relative, testCase.ToleranceOnSigma)
                << "sigma = " << testCase.Sigma << " came back as " << recovered;
        }
    }

    TEST(GaussianSplatPacking, AnAbsurdlyLargeSplatClampsInsteadOfBecomingInfinite)
    {
        // sqrt(65504) is a sigma of about 256 world units, above which the
        // covariance term overflows the half range. Unclamped it becomes +inf,
        // ConservativeSigma returns inf, `depth - radius` is -inf, and the
        // splat is dropped by EVERY camera with nothing logged anywhere -- the
        // worst kind of failure: silent, total and invisible to a screenshot.
        const std::array<f32, 6> cov =
            CovarianceFromScaleRotation(glm::log(glm::vec3(5000.0f)), glm::vec4(1.0f, 0.0f, 0.0f, 0.0f));
        EXPECT_TRUE(std::isfinite(cov[0])) << "the covariance itself should still be finite in f32";

        u32 a = 0;
        u32 b = 0;
        u32 c = 0;
        PackCovariance(cov, a, b, c);
        for (const f32 term : UnpackCovariance(a, b, c))
            EXPECT_TRUE(std::isfinite(term));

        const GpuSplat splat{ glm::vec3(0.0f), 0u, a, b, c, 0u };
        EXPECT_TRUE(std::isfinite(ConservativeSigma(splat)));
        EXPECT_GT(ConservativeSigma(splat), 0.0f);
    }

