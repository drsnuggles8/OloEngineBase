    TEST(GaussianSplatOrdering, DepthKeyIsMonotonicInDepth)
    {
        f32 previous = 0.0f;
        u32 previousKey = 0;
        for (const f32 depth : { 1e-4f, 0.05f, 0.5f, 1.0f, 7.5f, 1000.0f, 1e6f })
        {
            const u32 key = DepthSortKey(depth);
            EXPECT_GT(key, previousKey) << "depth " << depth << " after " << previous;
            previous = depth;
            previousKey = key;
        }
        // A non-positive or NaN depth sorts to the FAR end of the descending
        // order (the largest key), so a degenerate splat is drawn first and
        // painted over. Key 0 would be the near end and would paint over the
        // whole frame instead.
        EXPECT_EQ(DepthSortKey(-1.0f), 0xFFFFFFFFu);
        EXPECT_EQ(DepthSortKey(0.0f), 0xFFFFFFFFu);
        EXPECT_EQ(DepthSortKey(std::numeric_limits<f32>::quiet_NaN()), 0xFFFFFFFFu);
        EXPECT_LT(DepthSortKey(1e30f), 0xFFFFFFFFu) << "a real depth must never collide with the sentinel";
    }

    TEST(GaussianSplatOrdering, RadixSortMatchesAStableStdSort)
    {
        std::mt19937 rng(971);
        // Duplicate-heavy and all-equal inputs on purpose: a radix pass that is
        // skipped as uniform is where a descending sort implemented by
        // reversing the last pass silently returns ascending order.
        for (const u32 modulus : { 4u, 256u, 65536u, 0xFFFFFFFFu, 1u })
        {
            for (const sizet count : { sizet{ 0 }, sizet{ 1 }, sizet{ 2 }, sizet{ 1000 }, sizet{ 4097 } })
            {
                std::vector<u32> keys(count);
                std::vector<u32> indices(count);
                std::iota(indices.begin(), indices.end(), 0u);
                for (u32& key : keys)
                    key = (modulus == 1u) ? 12345u : (rng() % modulus);

                std::vector<std::pair<u32, u32>> reference(count);
                for (sizet i = 0; i < count; ++i)
                    reference[i] = { keys[i], indices[i] };
                std::stable_sort(reference.begin(), reference.end(),
                                 [](const auto& a, const auto& b)
                                 { return a.first > b.first; });

                std::vector<u32> keyScratch;
                std::vector<u32> indexScratch;
                RadixSortDescending(keys, indices, keyScratch, indexScratch);

                for (sizet i = 0; i < count; ++i)
                {
                    ASSERT_EQ(keys[i], reference[i].first) << "modulus " << modulus << " count " << count << " at " << i;
                    ASSERT_EQ(indices[i], reference[i].second)
                        << "unstable at modulus " << modulus << " count " << count << " index " << i;
                }
            }
        }
    }

    TEST(GaussianSplatOrdering, FixtureIsOrderedFarToNearAndIsDeterministic)
    {
        const fs::path path = FixturePath();
        ASSERT_FALSE(path.empty());
        SplatCloud cloud;
        ASSERT_TRUE(cloud.LoadPly(path).Ok);

        const glm::mat4 view = glm::lookAt(glm::vec3(0.0f, 1.0f, 7.0f), glm::vec3(0.0f), glm::vec3(0.0f, 1.0f, 0.0f));
        const glm::mat4 projection = glm::perspective(glm::radians(45.0f), 16.0f / 9.0f, 0.05f, 100.0f);
        const glm::vec2 viewport(1280.0f, 720.0f);

        ViewOrdering ordering;
        BuildViewOrdering(cloud, view, projection, viewport, ViewSettings{}, ordering);

        ASSERT_GT(ordering.Stats.Drawn, 3000u) << "most of the fixture should be visible from this pose";
        EXPECT_EQ(ordering.Indices.size(), ordering.Stats.Drawn);

        const glm::vec3 forward(-view[0][2], -view[1][2], -view[2][2]);
        const f32 forwardOffset = -view[3][2];
        f32 previousDepth = std::numeric_limits<f32>::max();
        for (const u32 index : ordering.Indices)
        {
            const f32 depth = glm::dot(forward, cloud.Splats()[index].Position) + forwardOffset;
            EXPECT_LE(depth, previousDepth + 1e-4f) << "draw order is not far-to-near";
            previousDepth = depth;
        }

        ViewOrdering again;
        BuildViewOrdering(cloud, view, projection, viewport, ViewSettings{}, again);
        EXPECT_EQ(ordering.Indices, again.Indices) << "the same camera must produce the same order";
    }

    TEST(GaussianSplatOrdering, CullsWhatIsBehindTheCameraAndOutsideTheFrustum)
    {
        const fs::path path = FixturePath();
        ASSERT_FALSE(path.empty());
        SplatCloud cloud;
        ASSERT_TRUE(cloud.LoadPly(path).Ok);

        const glm::mat4 projection = glm::perspective(glm::radians(45.0f), 16.0f / 9.0f, 0.05f, 100.0f);
        const glm::vec2 viewport(1280.0f, 720.0f);

        // Camera looking AWAY from the cloud: nothing may be drawn.
        const glm::mat4 away =
            glm::lookAt(glm::vec3(0.0f, 0.0f, 6.0f), glm::vec3(0.0f, 0.0f, 12.0f), glm::vec3(0.0f, 1.0f, 0.0f));
        ViewOrdering behind;
        BuildViewOrdering(cloud, away, projection, viewport, ViewSettings{}, behind);
        EXPECT_EQ(behind.Stats.Drawn, 0u);
        EXPECT_EQ(behind.Stats.BehindNearPlane + behind.Stats.FrustumCulled, cloud.Count());

        // Camera INSIDE the cloud: the shell behind the eye must be dropped
        // while the shell in front survives.
        const glm::mat4 inside =
            glm::lookAt(glm::vec3(0.0f), glm::vec3(0.0f, 0.0f, -1.0f), glm::vec3(0.0f, 1.0f, 0.0f));
        ViewOrdering within;
        BuildViewOrdering(cloud, inside, projection, viewport, ViewSettings{}, within);
        EXPECT_GT(within.Stats.BehindNearPlane, 0u);
        EXPECT_GT(within.Stats.Drawn, 0u);
        EXPECT_LT(within.Stats.Drawn, cloud.Count());
    }

    TEST(GaussianSplatLod, DistanceDropsSubPixelSplatsAndTheBudgetIsAHardCeiling)
    {
        const fs::path path = FixturePath();
        ASSERT_FALSE(path.empty());
        SplatCloud cloud;
        ASSERT_TRUE(cloud.LoadPly(path).Ok);

        const glm::mat4 projection = glm::perspective(glm::radians(45.0f), 16.0f / 9.0f, 0.05f, 1000.0f);
        const glm::vec2 viewport(1280.0f, 720.0f);

        // Monotone in distance: the further the camera, the fewer splats clear
        // the minimum screen extent. This is the "bounded LOD" claim.
        ViewSettings settings;
        settings.MinScreenExtentPixels = 2.0f;
        u32 previousDrawn = std::numeric_limits<u32>::max();
        for (const f32 distance : { 5.0f, 20.0f, 80.0f, 320.0f })
        {
            const glm::mat4 view =
                glm::lookAt(glm::vec3(0.0f, 0.0f, distance), glm::vec3(0.0f), glm::vec3(0.0f, 1.0f, 0.0f));
            ViewOrdering ordering;
            BuildViewOrdering(cloud, view, projection, viewport, settings, ordering);
            EXPECT_LE(ordering.Stats.Drawn, previousDrawn) << "distance " << distance;
            previousDrawn = ordering.Stats.Drawn;
        }
        EXPECT_LT(previousDrawn, cloud.Count() / 4u) << "LOD did nothing at 320 units";

        // The budget is a ceiling regardless of what survived the other tests.
        const glm::mat4 close =
            glm::lookAt(glm::vec3(0.0f, 0.0f, 5.0f), glm::vec3(0.0f), glm::vec3(0.0f, 1.0f, 0.0f));
        ViewSettings capped;
        capped.MaxSplats = 500;
        ViewOrdering ordering;
        BuildViewOrdering(cloud, close, projection, viewport, capped, ordering);
        EXPECT_EQ(ordering.Stats.Drawn, 500u);
        EXPECT_GT(ordering.Stats.OverBudget, 0u);

        // Still deterministic, and still ordered, under the cap.
        ViewOrdering again;
        BuildViewOrdering(cloud, close, projection, viewport, capped, again);
        EXPECT_EQ(ordering.Indices, again.Indices);
    }
