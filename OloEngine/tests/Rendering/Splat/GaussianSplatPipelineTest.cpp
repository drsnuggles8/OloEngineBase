// OLO_TEST_LAYER: L1
// =============================================================================
// GaussianSplatPipelineTest.cpp — CPU contracts for the Gaussian-splat spike
// (issue #971).
//
// Everything a splat cloud can get quietly WRONG lives on the CPU: the trainer
// stores opacity as a logit, scale as a logarithm, colour as an SH coefficient
// and rotation as a quaternion in (w, x, y, z) order, and every one of those is
// a decode where a plausible-looking cloud comes out of a wrong constant. A
// screenshot cannot tell a correctly decoded cloud from one whose quaternion
// components are rotated by one -- both look like a cloud of blobs. So the
// decode, the packing, the ordering and the LOD are pinned here, on the CPU,
// where a wrong answer is a failed assertion.
//
// The fixture is OloEditor/assets/tests/splat/fixture_discs.ply, generated by
// tools/splat/make_splat_fixture.py in the real INRIA property layout. The
// tests that check decoded VALUES check them against the generator's own inputs
// (0.90 opacity, 0.055 disc sigma, the three disc colours), which is what makes
// them a round-trip rather than a restatement of the implementation.
//
// No GPU: this file runs everywhere, including headless CI.
// =============================================================================

