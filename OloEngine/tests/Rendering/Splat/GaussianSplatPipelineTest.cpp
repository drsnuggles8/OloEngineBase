    TEST(GaussianSplatDecode, OpacityIsTheLogisticOfTheStoredLogit)
    {
        EXPECT_NEAR(SigmoidOpacity(0.0f), 0.5f, 1e-6f);
        EXPECT_NEAR(SigmoidOpacity(Logit(0.90f)), 0.90f, 1e-5f);
        EXPECT_NEAR(SigmoidOpacity(Logit(0.30f)), 0.30f, 1e-5f);

        // Saturation, not inf/NaN: the property is external data.
        EXPECT_TRUE(std::isfinite(SigmoidOpacity(1e30f)));
        EXPECT_TRUE(std::isfinite(SigmoidOpacity(-1e30f)));
        EXPECT_NEAR(SigmoidOpacity(1e30f), 1.0f, 1e-6f);
        EXPECT_NEAR(SigmoidOpacity(-1e30f), 0.0f, 1e-6f);
    }

    TEST(GaussianSplatDecode, ShBandZeroReproducesTheAuthoredColour)
    {
        // colour = 0.5 + C0 * f_dc, so f_dc = (colour - 0.5) / C0 must return
        // the colour. C0 = 0.5 * sqrt(1/pi) is the band-0 SH basis value.
        EXPECT_NEAR(kShC0, 0.5f * std::sqrt(1.0f / glm::pi<f32>()), 1e-7f);

        const glm::vec3 authored(0.90f, 0.20f, 0.18f);
        const glm::vec3 dc = (authored - 0.5f) / kShC0;
        const glm::vec3 decoded = ShDcToColor(dc);
        EXPECT_NEAR(decoded.r, authored.r, 1e-5f);
        EXPECT_NEAR(decoded.g, authored.g, 1e-5f);
        EXPECT_NEAR(decoded.b, authored.b, 1e-5f);
    }

    TEST(GaussianSplatDecode, IdentityRotationGivesADiagonalCovariance)
    {
        const glm::vec3 sigmas(0.2f, 0.05f, 0.01f);
        const std::array<f32, 6> cov =
            CovarianceFromScaleRotation(glm::log(sigmas), glm::vec4(1.0f, 0.0f, 0.0f, 0.0f));

        EXPECT_NEAR(cov[0], sigmas.x * sigmas.x, 1e-6f); // xx
        EXPECT_NEAR(cov[3], sigmas.y * sigmas.y, 1e-8f); // yy
        EXPECT_NEAR(cov[5], sigmas.z * sigmas.z, 1e-9f); // zz
        EXPECT_NEAR(cov[1], 0.0f, 1e-9f);                // xy
        EXPECT_NEAR(cov[2], 0.0f, 1e-9f);                // xz
        EXPECT_NEAR(cov[4], 0.0f, 1e-9f);                // yz
    }

    TEST(GaussianSplatDecode, QuaternionIsReadAsWXYZ)
    {
        // A 90-degree rotation about Z carries the x axis onto y, so the
        // largest variance must move from xx to yy. Reading the quaternion as
        // (x, y, z, w) instead leaves it in xx -- which is exactly the bug this
        // pins, and which no screenshot would reveal.
        const glm::vec3 sigmas(0.2f, 0.01f, 0.01f);
        const f32 halfAngle = glm::quarter_pi<f32>();
        const glm::vec4 quatWXYZ(std::cos(halfAngle), 0.0f, 0.0f, std::sin(halfAngle));

        const std::array<f32, 6> cov = CovarianceFromScaleRotation(glm::log(sigmas), quatWXYZ);
        EXPECT_NEAR(cov[3], sigmas.x * sigmas.x, 1e-5f); // yy now holds the long axis
        EXPECT_NEAR(cov[0], sigmas.y * sigmas.y, 1e-5f);
        EXPECT_NEAR(cov[5], sigmas.z * sigmas.z, 1e-8f);
    }

    TEST(GaussianSplatDecode, AnUnnormalisedOrDegenerateQuaternionStaysFinite)
    {
        const glm::vec3 logScale = glm::log(glm::vec3(0.1f));

        // Trainers do not normalise on write.
        const std::array<f32, 6> scaled = CovarianceFromScaleRotation(logScale, glm::vec4(7.0f, 0.0f, 0.0f, 0.0f));
        EXPECT_NEAR(scaled[0], 0.01f, 1e-6f);

        // All-zero is not a rotation; identity is the only safe reading.
        const std::array<f32, 6> zero = CovarianceFromScaleRotation(logScale, glm::vec4(0.0f));
        for (f32 term : zero)
            EXPECT_TRUE(std::isfinite(term));
        EXPECT_NEAR(zero[0], 0.01f, 1e-6f);

        // A huge log-scale must clamp rather than produce inf.
        const std::array<f32, 6> huge =
            CovarianceFromScaleRotation(glm::vec3(1000.0f), glm::vec4(1.0f, 0.0f, 0.0f, 0.0f));
        for (f32 term : huge)
            EXPECT_TRUE(std::isfinite(term));
    }

