    TEST(GaussianSplatImport, ReadsTheCheckedInFixture)
    {
        const fs::path path = FixturePath();
        ASSERT_FALSE(path.empty()) << "fixture_discs.ply not found from " << fs::current_path().string();

        SplatCloud cloud;
        const LoadResult result = cloud.LoadPly(path);
        ASSERT_TRUE(result.Ok) << result.Error;
        EXPECT_EQ(result.SplatsRead, 4096u);
        EXPECT_EQ(cloud.Count(), 4096u);

        // Generator geometry: three unit-radius discs inside a 1.6-radius shell.
        const BoundingBox bounds = cloud.Bounds();
        EXPECT_NEAR(bounds.Min.x, -1.6f, 0.05f);
        EXPECT_NEAR(bounds.Max.x, 1.6f, 0.05f);
        EXPECT_NEAR(bounds.Min.z, -1.6f, 0.05f);
        EXPECT_NEAR(bounds.Max.z, 1.6f, 0.05f);

        // The generator writes 45 f_rest_* and 3 normal properties this
        // representation drops: 48 floats of 62 per splat.
        EXPECT_EQ(result.DiscardedSourceBytes, static_cast<sizet>(48) * sizeof(f32) * 4096u);
        EXPECT_EQ(cloud.GpuBytes(), static_cast<sizet>(32) * 4096u);
    }

    TEST(GaussianSplatImport, FixtureDecodesToTheAuthoredColoursAndOpacities)
    {
        const fs::path path = FixturePath();
        ASSERT_FALSE(path.empty());
        SplatCloud cloud;
        ASSERT_TRUE(cloud.LoadPly(path).Ok);

        // The generator lays out 832 splats per disc, then 1600 shell splats.
        const glm::vec4 firstDisc = UnpackColorOpacity(cloud.Splats()[0].ColorOpacity);
        EXPECT_NEAR(firstDisc.r, 0.90f, 1.0f / 255.0f);
        EXPECT_NEAR(firstDisc.g, 0.20f, 1.0f / 255.0f);
        EXPECT_NEAR(firstDisc.b, 0.18f, 1.0f / 255.0f);
        EXPECT_NEAR(firstDisc.a, 0.90f, 1.0f / 255.0f);

        const glm::vec4 shell = UnpackColorOpacity(cloud.Splats()[2496].ColorOpacity);
        EXPECT_NEAR(shell.a, 0.30f, 1.0f / 255.0f);

        // Disc splats are oblate: one sigma an order of magnitude below the
        // other two. A cloud read with the covariance terms in the wrong order
        // loses that and renders as round blobs.
        const std::array<f32, 6> cov =
            UnpackCovariance(cloud.Splats()[0].CovXXXY, cloud.Splats()[0].CovXZYY, cloud.Splats()[0].CovYZZZ);
        const f32 trace = cov[0] + cov[3] + cov[5];
        const f32 smallest = std::min({ cov[0], cov[3], cov[5] });
        EXPECT_LT(smallest * 50.0f, trace) << "the flat axis of a disc splat is missing";
    }

    TEST(GaussianSplatImport, AsciiAndBinaryAgree)
    {
        PlyBuilder binary = PlyBuilder::Minimal();
        binary.Rows.push_back({ -4.0f, 0.5f, 9.0f, 1.0f, -1.0f, 0.25f, 2.0f, -2.0f, -3.0f, -4.0f, 0.7f, 0.1f, 0.2f,
                                0.3f });
        PlyBuilder ascii = binary;
        ascii.Format = "ascii";

        SplatCloud fromBinary;
        SplatCloud fromAscii;
        const std::vector<u8> binaryBytes = binary.Build();
        const std::vector<u8> asciiBytes = ascii.Build();
        ASSERT_TRUE(fromBinary.LoadPlyFromMemory(binaryBytes, "binary").Ok);
        ASSERT_TRUE(fromAscii.LoadPlyFromMemory(asciiBytes, "ascii").Ok);

        ASSERT_EQ(fromBinary.Count(), fromAscii.Count());
        for (u32 i = 0; i < fromBinary.Count(); ++i)
        {
            const GpuSplat& a = fromBinary.Splats()[i];
            const GpuSplat& b = fromAscii.Splats()[i];
            // std::to_string gives 6 decimals, so positions agree to ~1e-6 and
            // the packed fields (8-bit colour, half covariance) agree exactly.
            EXPECT_NEAR(a.Position.x, b.Position.x, 1e-5f);
            EXPECT_NEAR(a.Position.y, b.Position.y, 1e-5f);
            EXPECT_NEAR(a.Position.z, b.Position.z, 1e-5f);
            EXPECT_EQ(a.ColorOpacity, b.ColorOpacity);
            EXPECT_EQ(a.CovXXXY, b.CovXXXY);
        }
    }

    TEST(GaussianSplatImport, RejectsRatherThanHalfLoads)
    {
        const auto expectFailure = [](const std::vector<u8>& bytes, std::string_view expectedSubstring)
        {
            SplatCloud cloud;
            const LoadResult result = cloud.LoadPlyFromMemory(bytes, "case");
            EXPECT_FALSE(result.Ok) << "accepted a file it should have rejected";
            EXPECT_TRUE(result.Error.find(expectedSubstring) != std::string::npos)
                << "error was: " << result.Error << "\nexpected it to mention: " << expectedSubstring;
            EXPECT_EQ(cloud.Count(), 0u) << "a rejected load must leave the cloud empty";
        };

        {
            const std::string notPly = "OBJ file, actually\n";
            expectFailure({ notPly.begin(), notPly.end() }, "not a PLY");
        }
        {
            PlyBuilder big = PlyBuilder::Minimal();
            big.Format = "binary_big_endian";
            expectFailure(big.Build(), "unsupported PLY format");
        }
        {
            PlyBuilder missing = PlyBuilder::Minimal();
            missing.Properties.erase(missing.Properties.begin() + 6); // opacity
            for (std::vector<f32>& row : missing.Rows)
                row.erase(row.begin() + 6);
            expectFailure(missing.Build(), "opacity");
        }
        {
            std::vector<u8> truncated = PlyBuilder::Minimal().Build();
            truncated.resize(truncated.size() - 8);
            expectFailure(truncated, "truncated");
        }
        {
            PlyBuilder infinite = PlyBuilder::Minimal();
            infinite.Rows[0][0] = std::numeric_limits<f32>::infinity();
            expectFailure(infinite.Build(), "non-finite");
        }
        {
            // An element before `vertex` shifts the payload; refusing is the
            // only safe answer because the alternative renders a wrong cloud.
            std::string header = "ply\nformat ascii 1.0\nelement camera 1\nproperty float cx\nelement vertex 1\n";
            expectFailure({ header.begin(), header.end() }, "precedes 'vertex'");
        }
        {
            // A LYING COUNT MUST NOT BE BELIEVED FAR ENOUGH TO ALLOCATE ON.
            // 4294967295 vertices at 56 bytes each is 240 GB; sizing the
            // per-property arrays from the header before checking the file
            // length would throw std::bad_alloc where the contract promises a
            // LoadResult. A test that only shortened the payload by a few bytes
            // would not have caught it -- the allocation has to be the thing
            // that would blow up.
            PlyBuilder liar = PlyBuilder::Minimal();
            std::vector<u8> bytes = liar.Build();
            const std::string header(reinterpret_cast<const char*>(bytes.data()), bytes.size());
            const sizet pos = header.find("element vertex 1");
            ASSERT_NE(pos, std::string::npos);
            std::string patched = header;
            patched.replace(pos, std::string("element vertex 1").size(), "element vertex 4294967295");
            expectFailure({ patched.begin(), patched.end() }, "truncated");
        }
    }

    TEST(GaussianSplatImport, DecodesEveryIntegerTypeItAgreesToStrideOver)
    {
        // THE BUG THIS PINS reads correctly and produces nonsense. `PlyTypeSize`
        // accepts short/ushort/int/uint so their columns can be strided over,
        // and an earlier `ReadScalar` fell through to a 4-byte float memcpy for
        // all of them. Two failures follow: a 2-byte column is read two bytes
        // past its own slot -- past the end of the buffer if it is the last
        // property of the last record -- and a 4-byte integer is reinterpreted
        // as a float bit pattern, which for small integers is a denormal that
        // sails through the finiteness check.
        //
        // So a required property is declared as each accepted integer type in
        // turn and its decoded value is checked, rather than merely checking
        // that the file loads.
        for (const char* type : { "short", "ushort", "int", "uint", "uchar", "char", "double" })
        {
            PlyBuilder typed = PlyBuilder::Minimal();
            typed.Types.assign(typed.Properties.size(), "float");
            // `x` carries the integer; a value no float bit pattern coincides
            // with, and small enough for every type above to hold.
            const sizet xColumn = 0;
            typed.Types[xColumn] = type;
            typed.Rows[0][xColumn] = 7.0f;

            SplatCloud cloud;
            const std::vector<u8> bytes = typed.Build();
            const LoadResult result = cloud.LoadPlyFromMemory(bytes, type);
            ASSERT_TRUE(result.Ok) << type << ": " << result.Error;
            ASSERT_EQ(cloud.Count(), 1u) << type;
            EXPECT_NEAR(cloud.Splats()[0].Position.x, 7.0f, 1e-5f) << "property declared as " << type;

            // The rest of the record must still land where the stride says, or
            // the mis-sized read has quietly shifted everything after it.
            EXPECT_NEAR(cloud.Splats()[0].Position.y, 2.0f, 1e-5f) << "stride broke after a " << type;
            EXPECT_NEAR(cloud.Splats()[0].Position.z, 3.0f, 1e-5f) << "stride broke after a " << type;
        }
    }

    TEST(GaussianSplatImport, AnIntegerColumnAtTheEndOfTheRecordIsNotOverread)
    {
        // The out-of-bounds half of the same bug, isolated: a 2-byte property as
        // the LAST column of the LAST record has only two bytes behind it, so a
        // 4-byte read runs off the end of the file image. It is the case a
        // sanitizer would catch and a normal run would not.
        PlyBuilder tail = PlyBuilder::Minimal();
        tail.Properties.push_back("confidence");
        tail.Types.assign(tail.Properties.size(), "float");
        tail.Types.back() = "ushort";
        tail.Rows[0].push_back(42.0f);

        SplatCloud cloud;
        const std::vector<u8> bytes = tail.Build();
        const LoadResult result = cloud.LoadPlyFromMemory(bytes, "trailing-ushort");
        ASSERT_TRUE(result.Ok) << result.Error;
        EXPECT_EQ(cloud.Count(), 1u);
        EXPECT_NEAR(cloud.Splats()[0].Position.x, 1.0f, 1e-5f);
        // Two bytes of the record are not this representation's, so they are
        // counted as discarded rather than silently absorbed.
        EXPECT_EQ(result.DiscardedSourceBytes, 2u);
    }

    TEST(GaussianSplatImport, ToleratesExtraPropertiesAndReordering)
    {
        // Exporters differ. The reader matches by name, so an unknown column in
        // the middle and a different block order must both still work.
        PlyBuilder shuffled;
        shuffled.Properties = { "rot_0", "rot_1", "rot_2", "rot_3", "confidence", "x", "y",
                                "z", "junk", "f_dc_0", "f_dc_1", "f_dc_2", "scale_0", "scale_1",
                                "scale_2", "opacity" };
        shuffled.Rows.push_back({ 1.0f, 0.0f, 0.0f, 0.0f, 42.0f, 5.0f, 6.0f, 7.0f, -1.0f, 0.0f, 0.0f, 0.0f, -3.0f,
                                  -3.0f, -3.0f, 0.0f });

        SplatCloud cloud;
        const std::vector<u8> bytes = shuffled.Build();
        const LoadResult result = cloud.LoadPlyFromMemory(bytes, "shuffled");
        ASSERT_TRUE(result.Ok) << result.Error;
        ASSERT_EQ(cloud.Count(), 1u);
        EXPECT_NEAR(cloud.Splats()[0].Position.x, 5.0f, 1e-6f);
        EXPECT_NEAR(cloud.Splats()[0].Position.z, 7.0f, 1e-6f);
        EXPECT_NEAR(UnpackColorOpacity(cloud.Splats()[0].ColorOpacity).a, 0.5f, 1.0f / 255.0f);
        // Two extra float columns per splat that this representation drops.
        EXPECT_EQ(result.DiscardedSourceBytes, 2u * sizeof(f32));
    }

