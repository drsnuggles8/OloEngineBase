class SceneWriter:
    def __init__(self, name, id_base, header_note, settings):
        self.name = name
        self.parts = []
        self.next_id = id_base
        self.count = 0
        self.header_note = header_note
        self.settings = settings

    def entity(self, tag, translation=(0, 0, 0), rotation=(0, 0, 0),
               scale=(1, 1, 1), components="", comment=None):
        eid = self.next_id
        self.next_id += 1
        self.count += 1
        if comment:
            self.parts.append(f"  # {comment}\n")
        self.parts.append(
            f"  - Entity: {eid}\n"
            f"    TagComponent:\n"
            f"      Tag: {tag}\n"
            f"    TransformComponent:\n"
            f"      Translation: {vec(translation)}\n"
            f"      Rotation: {vec(rotation)}\n"
            f"      Scale: {vec(scale)}\n"
            + components
        )
        return eid

    def text(self):
        # A blank note line emits a bare "#", never "# " — pre-commit's
        # trailing-whitespace hook would strip the space and the committed
        # scene would stop matching this generator's output byte for byte,
        # which is the property that makes "regenerate and diff" meaningful.
        def comment(line):
            return f"# {line}\n" if line else "#\n"

        header = (
            f"Scene: {self.name}.olo\n"
            "# ─────────────────────────────────────────────────────────────────────────────\n"
            + comment(self.header_note[0])
        )
        for line in self.header_note[1:]:
            header += comment(line)
        header += (
            "#\n"
            "# GENERATED by OloEngine/tests/scripts/generate_reference_fixture_scenes.py\n"
            "# (issue #1239) — edit the generator and regenerate rather than hand-editing.\n"
            "# ─────────────────────────────────────────────────────────────────────────────\n"
        )
        return header + self.settings + "Entities:\n" + "".join(self.parts)


