def build_reference_head():
    w = SceneWriter(
        "ReferenceHead", 1_239_000_001_000_000, HEAD_NOTE,
        settings(ssao=True, ssr=True, ssgi=False, bloom=0.25, fog=NO_FOG,
                 wind=wind_settings(False)),
    )

    w.entity("Camera", (0, 1.1, 3.1), (-0.05, 0, 0), (1, 1, 1), camera(),
             comment="── Camera (scene camera; capture manifests pose the EDITOR camera) ──")
    # SKYBOX OFF, IBL ON. A visible environment turned the first capture of this
    # fixture into a photo of the Newport Loft interior with two heads in it:
    # the backlit camera read as "well lit from behind by a room", and no
    # lighting change was legible against a busy backdrop. A measurement fixture
    # wants a controlled background and a rig that drives the image, so the HDR
    # stays as the fill source and stops being the picture.
    w.entity("Skybox", components=environment_map(ibl=0.3, skybox=False),
             comment="── Studio IBL (Newport Loft HDR) — fill only, skybox NOT drawn ──")

    # Key light: high front-left, the only shadow caster. A single directional
    # keeps the shadow term unambiguous — two would make "which light made
    # this shadow?" unanswerable from a single AOV.
    # With the skybox off the rig has to carry the image, so the key and rim
    # are strong enough to read against an unlit background rather than being
    # a nudge on top of a bright environment.
    w.entity("Key Light", components=dir_light((-0.45, -0.8, -0.42), (1, 0.96, 0.90), 6.0,
                                               shadows=True, max_shadow_distance=30, cascade_lambda=0.85),
             comment="── Key: high front-right-above, sole shadow caster ──")
    # Rim/back light behind the subjects — what makes the BACKLIT camera a
    # real backlit shot rather than a dark one.
    w.entity("Rim Light", (0, 1.65, -1.9), components=point_light((0.82, 0.90, 1.0), 45.0, 7.0),
             comment="── Rim: behind and above, cool — the backlit camera's subject ──")
    w.entity("Fill Light", (1.9, 0.85, 1.9), components=point_light((1.0, 0.93, 0.84), 14.0, 8.0),
             comment="── Fill: low warm bounce, no shadows ──")

    # Subjects. Separation and scale are set so BOTH fit the 42-degree frontal
    # frame with margin: Suzanne is ~2.7 units wide before scaling, and the
    # first capture of this fixture clipped its left ear at +-1.15 / 0.55.
    for tag, x, yaw, path in (
        ("Suzanne", -0.95, 0.35, "assets/models/Suzanne/glTF/Suzanne.gltf"),
        ("DamagedHelmet", 0.95, -0.35, "assets/models/DamagedHelmet/glTF/DamagedHelmet.gltf"),
    ):
        w.entity(tag, (x, 1.05, 0), (0, yaw, 0), (0.5, 0.5, 0.5), model(path),
                 comment=("── Subject A: organic head geometry (Suzanne, CC0) ──" if x < 0 else
                          "── Subject B: textured PBR detail (DamagedHelmet, CC-BY 4.0) ──"))

    # Plinths + floor: mid-grey, matte, so the subjects own the frame.
    for tag, x in (("Plinth A", -0.95), ("Plinth B", 0.95)):
        w.entity(tag, (x, 0.33, 0), (0, 0, 0), (0.58, 0.66, 0.58),
                 mesh(1) + material((0.20, 0.20, 0.21), 0.0, 0.85))
    w.entity("Floor", (0, -0.02, 0), (0, 0, 0), (24, 0.04, 24),
             mesh(1) + material((0.16, 0.16, 0.17), 0.0, 0.75),
             comment="── Matte floor: contact shadow + a little bounce, no reflection show ──")
    return w


def build_animal(name, note, subject_components, subject_transform, subject_tag):
    w = SceneWriter(
        name,
        1_239_000_002_000_000 if name == "AnimalShortCoat" else 1_239_000_003_000_000,
        note,
        settings(ssao=True, ssr=False, ssgi=False, bloom=0.25, fog=NO_FOG,
                 wind=wind_settings(True, speed=4.0, gust=0.3)),
    )
    w.entity("Camera", (0, 0.8, 2.6), (-0.05, 0, 0), (1, 1, 1), camera(),
             comment="── Camera (scene camera; capture manifests pose the EDITOR camera) ──")
    # Skybox off for the same reason as the head fixture: the first capture of
    # these fixtures was a photograph of the Newport Loft window with a small
    # animal in front of it, and a blown-out background makes a coat silhouette
    # unjudgeable. The HDR stays as the fill source.
    w.entity("Skybox", components=environment_map(ibl=0.35, skybox=False),
             comment="── IBL fill only (Newport Loft HDR); skybox NOT drawn ──")
    # Low sun from behind-left: gives the grazing camera a long raking light
    # across the flank and the backlit camera a true rim.
    w.entity("Sun", components=dir_light((-0.55, -0.35, -0.76), (1, 0.92, 0.80), 5.5,
                                         shadows=True, max_shadow_distance=60, cascade_lambda=0.88),
             comment="── Low sun from behind-left: raking flank light + a real rim ──")
    w.entity("Fill Light", (2.6, 1.7, 2.8), components=point_light((0.85, 0.90, 1.0), 9.0, 10.0),
             comment="── Cool sky fill from the camera side ──")

    translation, rotation, scale = subject_transform
    w.entity(subject_tag, translation, rotation, scale, subject_components,
             comment="── THE SUBJECT ──")

    w.entity("Ground", (0, -0.02, 0), (0, 0, 0), (60, 0.04, 60),
             mesh(1) + material((0.24, 0.26, 0.18), 0.0, 0.92),
             comment="── Ground: matte earth, identical in both animal fixtures ──")
    return w


