def procedural_sky(sun_direction, turbidity=2.6, ibl=0.9, exposure=0.10):
    """Physically-based sky instead of an HDR probe, for the OUTDOOR fixtures.

    Two reasons, and the second is the important one:
      * the first capture of the meadow rendered the Newport Loft interior
        CEILING above the grass, because an indoor probe is an indoor probe;
      * a procedural sky carries NO third-party rights at all, so the
        vegetation fixtures' provenance lists shrink to assets this repository
        actually owns. The head and animal fixtures keep the HDR because a
        studio probe is what a studio rig wants.

    SunDirection points TOWARD the sun, the opposite convention to
    DirectionalLightComponent::Direction (which is where the light travels).
    The caller passes the negated light direction so the sky's sun disk sits
    where the shadows say it should — otherwise the backlit camera looks into
    an empty patch of sky.
    """
    return (
        "    ProceduralSkyComponent:\n"
        f"      SunDirection: {vec(sun_direction)}\n"
        f"      Turbidity: {f(turbidity)}\n"
        f"      Exposure: {f(exposure)}\n"
        "      SunIntensity: 1\n"
        "      SunDiskSize: 1\n"
        "      ShowSunDisk: true\n"
        "      EnableSkybox: true\n"
        "      EnableIBL: true\n"
        f"      IBLIntensity: {f(ibl)}\n"
        "      CubemapResolution: 256\n"
    )


def dir_light(direction, color=(1, 0.95, 0.88), intensity=3.0, shadows=True,
              max_shadow_distance=120.0, cascade_lambda=0.92):
    return (
        "    DirectionalLightComponent:\n"
        f"      Direction: {vec(direction)}\n"
        f"      Color: {vec(color)}\n"
        f"      Intensity: {f(intensity)}\n"
        f"      CastShadows: {'true' if shadows else 'false'}\n"
        "      ShadowDepthBiasTexels: 2\n"
        # Engine default (0.01), deliberately NOT the 0.1 the sample scenes
        # author: a 10x normal bias detaches contact shadows from their caster
        # (#1119), which would corrupt the very thing a head fixture measures.
        "      ShadowNormalBias: 0.01\n"
        f"      MaxShadowDistance: {f(max_shadow_distance)}\n"
        f"      CascadeSplitLambda: {f(cascade_lambda)}\n"
        "      CascadeDebugVisualization: false\n"
    )


def point_light(color, intensity, range_, cast_shadows=False):
    # Every field is written out, defaults included: a benchmark fixture's
    # lighting is part of the measurement, so "what was Attenuation?" must be
    # answerable from the scene file rather than from the engine's defaults at
    # the time the capture happened.
    return (
        "    PointLightComponent:\n"
        f"      Color: {vec(color)}\n"
        f"      Intensity: {f(intensity)}\n"
        f"      Range: {f(range_)}\n"
        "      Attenuation: 1\n"
        f"      CastShadows: {'true' if cast_shadows else 'false'}\n"
        "      ShadowBias: 0.005\n"
        "      ShadowNormalBias: 0.01\n"
    )


