# Emits the five REFERENCE FIXTURE scenes for issue #1239:
#   OloEditor/SandboxProject/Assets/Scenes/Benchmark/
#     ReferenceHead.olo      a head-scale subject under a pinned studio rig
#     AnimalShortCoat.olo    Khronos Fox — skinned, animated, short coat
#     AnimalLongCoat.olo     procedural long-coated quadruped stand-in
#     Meadow.olo             open grass/flower field, wind-driven
#     Woodland.olo           dense tree canopy with impostors, wind-driven
#
# WHAT THESE FIXTURES ARE FOR
# ---------------------------
# They are the measuring instrument for the AAA characters-and-flora epic
# (#1225), not a showcase. Issue #1239's own scope boundary: "Fixtures
# initially show current limitations and are upgraded by feature owners."
#
# So the head has no subsurface scattering, the long coat is a solid shell,
# and the meadow is alpha-masked billboards — because that is what the engine
# does TODAY. Each of those is the baseline that #1230, #1232, #1241, #1244,
# #1246, #1251, #1254 and #1258 will be measured against. Improving a fixture
# to make its capture look better destroys the baseline it exists to record.
#
# Like generate_courtyard_scene.py, these scenes are COMMITTED and this
# generator exists because the foliage layer tables and the lighting rigs are
# unmaintainable by hand — not because they are regenerated per run. Output is
# byte-stable: fixed seed, deterministic float formatting, no timestamps.
#
#   python OloEngine/tests/scripts/generate_reference_fixture_scenes.py
#
# Every YAML key below is either verified against SceneSerializer.cpp or
# copied from a committed scene that uses it (fox.olo, PBRReference.olo,
# Courtyard.olo, FoliageGenerationTest.olo, Drift.olo).
# =============================================================================

