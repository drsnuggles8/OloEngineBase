def main():
    ap = argparse.ArgumentParser(
        description="Generate the #1239 reference fixture benchmark scenes (.olo)")
    ap.add_argument("--out-dir", type=pathlib.Path, default=SCENE_DIR)
    ap.add_argument("--only", choices=sorted(BUILDERS), default=None)
    args = ap.parse_args()

    args.out_dir.mkdir(parents=True, exist_ok=True)
    names = [args.only] if args.only else list(BUILDERS)
    for name in names:
        w = BUILDERS[name]()
        path = args.out_dir / f"{name}.olo"
        path.write_text(w.text(), encoding="utf-8", newline="\n")
        print(f"{path} ({w.count} entities)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
