def tower_ring(rng, n=48, cx=60.0, cz=0.0, r_min=420.0, r_max=520.0):
    # One InstancedMeshComponent (InstancingDemo layout): column-major mat4
    # rows [c*sx, 0, sin*sx, 0, 0, sy, 0, 0, -sin*sz, 0, c*sz, 0, tx, ty, tz, 1]
    # (Y-yaw * nonuniform scale). Unit cube primitive is centred, so
    # ty = sy/2 + ground top (-0.45).
    header = (
        "    InstancedMeshComponent:\n"
        "      Primitive: 1\n"
        "      FrustumCullPerInstance: true\n"
        "      CastShadows: false\n"
        "      CullDistance: 0\n"
        "      Instances:\n"
    )
    rows = []
    for i in range(n):
        ang = (i / n) * 2.0 * math.pi + rng.uniform(-0.03, 0.03)
        radius = rng.uniform(r_min, r_max)
        tx = cx + radius * math.cos(ang)
        tz = cz + radius * math.sin(ang)
        sx = rng.uniform(14.0, 26.0)
        sz = rng.uniform(14.0, 26.0)
        sy = rng.uniform(35.0, 85.0)
        ty = sy / 2.0 - 0.45
        yaw = rng.uniform(0.0, math.pi)
        c, s = math.cos(yaw), math.sin(yaw)
        shade = rng.uniform(0.35, 0.55)
        col = (shade * 0.9, shade * 0.95, shade * 1.05)
        rows.append(
            f"        - Transform: [{f(c * sx)}, 0, {f(s * sx)}, 0, "
            f"0, {f(sy)}, 0, 0, "
            f"{f(-s * sz)}, 0, {f(c * sz)}, 0, "
            f"{f(tx)}, {f(ty)}, {f(tz)}, 1]\n"
            f"          Color: [{f(col[0])}, {f(col[1])}, {f(col[2])}, 1]\n"
        )
    return header + "".join(rows)


