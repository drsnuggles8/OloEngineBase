class SceneWriter:
    def __init__(self):
        self.parts = []
        self.next_id = ID_BASE
        self.count = 0

    def entity(self, tag, translation=(0, 0, 0), rotation=(0, 0, 0),
               scale=(1, 1, 1), components="", comment=None):
        eid = self.next_id
        self.next_id += 1
        self.count += 1
        if comment:
            self.parts.append(f"  # {comment}\n")
        self.parts.append(
            f"  - Entity: {eid}\n"
            f"    TagComponent:\n"
            f"      Tag: {tag}\n"
            f"    TransformComponent:\n"
            f"      Translation: {vec(translation)}\n"
            f"      Rotation: {vec(rotation)}\n"
            f"      Scale: {vec(scale)}\n"
            + components
        )
        return eid

    def text(self):
        return HEADER + SETTINGS + "Entities:\n" + "".join(self.parts)


