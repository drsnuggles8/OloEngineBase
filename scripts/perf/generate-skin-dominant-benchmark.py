def base_manifest(manifest_id: str, path: str, presets: dict, diffusion: bool, upscale: str,
                  asset_list: list[dict]) -> dict:
    arm = "full skin stack" if diffusion else "skin diffusion switched off (control arm)"
    return {
        "ManifestVersion": 2,
        "Id": manifest_id,
        "Product": "diagnostic",
        "Scene": "Scenes/Benchmark/SkinDominant.olo",
        "Description": (f"#1396 skin-dominant workload, {arm}: 28 scanned heads with the reference skin profile "
                        "filling a 1080p frame, so SkinDiffusionPass is measurable above the run-to-run spread."),
        "Backends": {"Supported": ["opengl", "vulkan"], "Features": {"vulkan": {"UnsupportedAttachments": []}}},
        "Cameras": cameras(),
        "Output": {"Resolution": [1920, 1080], "RenderScale": 1.0},
        "RendererSettings": {"Path": path, "EnableDDGI": False, "TAAEnabled": True,
                             "RayTracedShadowsEnabled": False, "VirtualShadowMaps": False,
                             "SkinDiffusion": diffusion, "MSAASampleCount": 1, "Upscale": upscale,
                             "UpscaleTechnique": "Spatial"},
        "Exposure": {"Mode": "Manual", "Exposure": 1.0},
        "Determinism": {"Seed": 1396, "StartTimeSeconds": 12.0, "FixedDtSeconds": DT},
        "Warmup": {"Frames": 96, "PerFeature": {"TAA": 8, "SSAO": 4, "Exposure": 30}},
        "Measurement": {"Frames": 300, "DeadlineMs": GATE_MS},
        "Attachments": ATTACHMENTS,
        "Tolerance": {"RepeatRmse": 0.0},
        "Assets": asset_list,
        "Presets": presets,
    }


def manifests(scene_sha: str) -> dict[str, dict]:
    asset_list = assets(scene_sha)
    result: dict[str, dict] = {}
    for slug, path, gl_preset, vk_preset in PATHS:
        presets = {"opengl": gl_preset, "vulkan": vk_preset}
        for diffusion, suffix in ((True, ""), (False, "-diffusion-off")):
            mid = f"skin-dominant-{slug}{suffix}"
            result[mid] = base_manifest(mid, path, presets, diffusion, "Off", asset_list)
    up = "skin-dominant-deferred-upscale-quality"
    result[up] = base_manifest(up, "Deferred", {"opengl": "gl-deferred-native", "vulkan": "vk-deferred-native"},
                               True, "Quality", asset_list)
    return result


def render_manifest(manifest: dict) -> str:
    return ("# GENERATED by scripts/perf/generate-skin-dominant-benchmark.py (#1396). Do not edit by hand.\n"
            + yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="fail if committed output is stale")
    args = parser.parse_args()

    scene = compose()
    scene_sha = hashlib.sha256(scene.encode("utf-8")).hexdigest()
    outputs = {OUTPUT: scene}
    outputs.update({MANIFESTS / f"{mid}.yaml": render_manifest(m) for mid, m in manifests(scene_sha).items()})

    stale = []
    for path, text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(path.relative_to(ROOT))
    if stale:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
