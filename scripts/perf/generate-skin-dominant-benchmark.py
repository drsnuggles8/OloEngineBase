def fmt(value: float) -> str:
    text = f"{value:.4f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def head_centre(row: int, column: int) -> tuple[float, float, float]:
    return ((column - (COLUMNS - 1) / 2) * COLUMN_PITCH, row * ROW_RISE, -row * ROW_DEPTH)


def compose() -> str:
    parts = [HEADER]
    for row in range(ROWS):
        for column in range(COLUMNS):
            x, y, z = head_centre(row, column)
            parts.append(HEAD.format(uuid=1396000002000000 + row * 100 + column, row=row, column=column,
                                     x=fmt(x), y=fmt(y - HEAD_DROP), z=fmt(z), scale=fmt(HEAD_SCALE),
                                     profile=SKIN_PROFILE))
    return "".join(parts)


