"""Compose the #1396 skin-dominant benchmark scene and its capture manifests.

#1222 asks for the skin stack's per-pass GPU cost on named hardware, and #1259's
acceptance workload could not resolve it: one head at conversational distance is
a small fraction of a 1080p frame, and its SkinDiffusionPass time (0.15-0.45 ms
p50 across runs) was as wide as the value. This scene makes skin the frame:

* a stepped "choir" of 28 copies of the scanned head (`Head.fbx`, the subject of
  `Scenes/DigitalHuman.olo`) wearing the same `ReferenceHead.oloskin` and
  thickness map, so every head runs the full stack (diffusion, transmission,
  layered specular);
* no backdrop and no environment, so every covered pixel is skin and the
  coverage of a capture is its count of finite depths;
* one shadowed directional key and one unshadowed fill, so the passes skin
  rides with (G-Buffer, lighting, shadows) stay small beside it.

Two cameras: `face-fill` frames the front-row middle face so it fills the frame
height (neighbouring faces fill the sides), and `crowd` holds the whole choir.

Manifests, per raster path: the full stack (`skin-dominant-<path>`), the same
scene with the diffusion switched off (`...-diffusion-off`, the control arm), and
on Deferred one upscaled cell (`skin-dominant-deferred-upscale-quality`), because
the diffusion's targets follow the scene band. Run from the repository root:

    python scripts/perf/generate-skin-dominant-benchmark.py

`--check` fails if the committed output differs from what this script writes.
The campaign that measures these is in
docs/testing/evidence/skin-stack-cost-1396/README.md.
"""

