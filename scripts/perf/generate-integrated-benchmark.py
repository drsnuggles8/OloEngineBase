"""Compose the committed integrated renderer fixture from existing scene content.

The source scenes own their assets and authored components. This script joins
the moving animal population, meadow terrain/flora, local lights and a water patch;
it does not invent substitutes for a missing representation.
"""

from pathlib import Path
import hashlib
import re
import yaml


ROOT = Path(__file__).resolve().parents[2]
SCENES = ROOT / "OloEditor/SandboxProject/Assets/Scenes/Benchmark"
ENTITY_START = re.compile(r"(?m)^  - Entity: ")


def entities(path: Path) -> list[str]:
    text = path.read_text(encoding="utf-8")
    if "\nEntities:\n" not in text:
        raise ValueError(f"missing Entities block: {path}")
    body = text.split("\nEntities:\n", 1)[1]
    starts = [match.start() for match in ENTITY_START.finditer(body)]
    return [body[start:end].rstrip() for start, end in zip(starts, starts[1:] + [len(body)])]


def main() -> None:
    animal = SCENES / "AnimalPopulation.olo"
    meadow = SCENES / "Meadow.olo"
    courtyard = SCENES / "Courtyard.olo"
    coast = SCENES / "OceanCoast.olo"
    animal_text = animal.read_text(encoding="utf-8")
    base, postprocess = animal_text.split("\nPostProcessSettings:\n", 1)
    base = (
        "Scene: IntegratedRenderer\n"
        "# GENERATED by scripts/perf/generate-integrated-benchmark.py.\n"
        "# This fixture combines the AnimalPopulation moving herd and pathless Hero with\n"
        "# Meadow terrain and foliage, Courtyard local lights, and an OceanCoast water patch.\n"
        "# The capture manifest adds deterministic Hero and point-light trajectories.\n"
        "# Imported grooms are unbound to the Fox bodies and appear as small blobs;\n"
        "# this scene exercises scheduling and rendering load, not groom quality.\n"
        "Entities:" + base.split("\nEntities:", 1)[1]
    )
    chosen = []
    for block in entities(meadow):
        tag = re.search(r"(?m)^      Tag: (.+)$", block)
        if tag and tag.group(1) in {"Sky", "Meadow Terrain"}:
            if tag.group(1) == "Meadow Terrain":
                # AnimalPopulation bodies are authored at world Y=0. The
                # procedural meadow rises several metres at the herd center;
                # move its ground/foliage down so the subjects remain visible.
                block = block.replace("Translation: [-96, 0, -96]",
                                      "Translation: [-96, -5, -96]", 1)
            chosen.append(block)
    for block in entities(courtyard):
        tag = re.search(r"(?m)^      Tag: (.+)$", block)
        if tag and tag.group(1) in {"PLight Shadow 0", "PLight Shadow 1", "Spot Gallery 0", "Spot Gallery 1"}:
            positions = {"PLight Shadow 0": "[-3, 3, 0]", "PLight Shadow 1": "[3, 3, 0]",
                         "Spot Gallery 0": "[-3, 4, -8]", "Spot Gallery 1": "[3, 4, -8]"}
            block = re.sub(r"(?m)^      Translation: \[[^\]]+\]$",
                           "      Translation: " + positions[tag.group(1)], block, count=1)
            chosen.append(block.replace("      CastShadows: true", "      CastShadows: true\n      RayTracedShadows: true", 1))
    if len(chosen) != 6:
        raise ValueError(f"expected two meadow and four light entities, got {len(chosen)}")
    ocean = [block for block in entities(coast) if "Tag: Ocean\n" in block]
    if len(ocean) != 1:
        raise ValueError("expected one authored ocean entity")
    water = ocean[0].replace("Translation: [0, 0, 0]", "Translation: [7, 1.5, 7]", 1)
    water = water.replace("WorldSizeX: 1600", "WorldSizeX: 10", 1)
    water = water.replace("WorldSizeZ: 1600", "WorldSizeZ: 10", 1)
    water = water.replace("GridResolutionX: 640", "GridResolutionX: 128", 1)
    water = water.replace("GridResolutionZ: 640", "GridResolutionZ: 128", 1)
    output = SCENES / "IntegratedRenderer.olo"
    output.write_text(
        base.rstrip() + "\n  # Integrated additions from Meadow, Courtyard lights and OceanCoast.\n"
        + "\n".join(chosen + [water]) + "\nPostProcessSettings:\n" + postprocess,
        encoding="utf-8",
        newline="\n",
    )
    print(output)

    manifests = ROOT / "OloEditor/assets/benchmark/manifests"
    source = yaml.safe_load((manifests / "animal-population.diagnostic.yaml").read_text(encoding="utf-8"))
    meadow_source = yaml.safe_load((manifests / "meadow.diagnostic.yaml").read_text(encoding="utf-8"))
    assets = {asset["Path"]: asset for asset in source["Assets"] + meadow_source["Assets"]}
    scene_asset_path = "SandboxProject/Assets/Scenes/Benchmark/IntegratedRenderer.olo"
    assets[scene_asset_path] = {
        "Path": scene_asset_path,
        "Origin": "generated in-repo from AnimalPopulation, Meadow, Courtyard and OceanCoast",
        "License": "repository license (no third-party rights)",
        "Redistribution": "committed",
        "LicenseVerified": "in-repo-file",
        "Version": "generated",
        "Sha256": hashlib.sha256(output.read_bytes()).hexdigest(),
        "Units": "metres",
        "UpAxis": "+Y",
        "ColorSpace": "n/a",
        "Acquisition": "run python scripts/perf/generate-integrated-benchmark.py",
    }
    source["Assets"] = list(assets.values())
    source["Scene"] = "Scenes/Benchmark/IntegratedRenderer.olo"
    source["Description"] = ("Integrated moving animal, terrain/foliage, local-shadow and water workload. "
                             "Animal grooms are unbound to the Fox bodies and are not a quality reference.")
    source["Cameras"] = [
        {"Id": "stationary", "Position": [0.0, 3.4, 16.0], "YawDegrees": 0.0,
         "PitchDegrees": 6.0, "FovDegrees": 50.0, "Near": 0.05, "Far": 400.0},
        {"Id": "dolly", "Position": [0.0, 3.4, 22.0], "YawDegrees": 0.0,
         "PitchDegrees": 6.0, "FovDegrees": 50.0, "Near": 0.05, "Far": 400.0,
         "Motion": {"VelocityPerSecond": [0.0, 0.0, -5.0],
                    "YawRateDegreesPerSecond": 0.0, "PitchRateDegreesPerSecond": 0.0}},
        {"Id": "rapid-turn", "Position": [0.0, 4.0, 14.0], "YawDegrees": -90.0,
         "PitchDegrees": 5.0, "FovDegrees": 60.0, "Near": 0.05, "Far": 400.0,
         "Motion": {"VelocityPerSecond": [0.0, 0.0, 0.0],
                    "YawRateDegreesPerSecond": 60.0, "PitchRateDegreesPerSecond": 0.0}},
    ]
    source.pop("Camera", None)
    source["Output"] = {"Resolution": [1920, 1080], "RenderScale": 1.0}
    source["Warmup"] = {"Frames": 64, "PerFeature": {"TAA": 8, "SSAO": 4, "Exposure": 30}}
    source["Measurement"] = {"Frames": 180, "DeadlineMs": 33.333}
    source["EntityMotion"] = [
        {"Tag": "PLight Shadow 0", "Origin": [-3.0, 3.0, 0.0], "Amplitude": [2.0, 0.0, 1.0],
         "FrequencyHz": 0.35, "PhaseRadians": 0.0},
        {"Tag": "Hero", "Origin": [0.0, 0.0, 5.6], "Amplitude": [1.0, 0.0, 0.5],
         "FrequencyHz": 0.18, "PhaseRadians": 0.0},
    ]
    source["Attachments"] = [
        {"Name": "Beauty", "Source": "UIComposite", "Format": "png"},
        {"Name": "SceneColorHDR", "Source": "SceneColor", "Format": "hdr"},
        {"Name": "Albedo", "Source": "GBufferAlbedo", "Format": "png"},
        {"Name": "Normals", "Source": "GBufferNormal", "Format": "png", "Normalize": "none"},
        {"Name": "Velocity", "Source": "Velocity", "Format": "png", "Normalize": "on"},
        {"Name": "SceneDepth", "Source": "SceneDepth", "Format": "hdr"},
    ]
    for name, path, backend, rt in [
        ("integrated-forward.yaml", "Forward", ["opengl", "vulkan"], False),
        ("integrated-forward-plus.yaml", "ForwardPlus", ["opengl", "vulkan"], False),
        ("integrated-deferred.yaml", "Deferred", ["opengl", "vulkan"], False),
        ("integrated-hybrid.yaml", "Deferred", ["vulkan"], True),
    ]:
        manifest = dict(source)
        manifest["Id"] = name.removesuffix(".yaml")
        manifest["Backends"] = {"Supported": backend,
                                "Features": {"vulkan": {"UnsupportedAttachments": []}}}
        preset_ids = {
            "opengl": {"Forward": "gl-forward-native", "ForwardPlus": "gl-forward-plus-native",
                       "Deferred": "gl-deferred-native"}[path],
            "vulkan": ("vk-hybrid-native" if rt else
                       {"Forward": "vk-forward-native", "ForwardPlus": "vk-forward-plus-native",
                        "Deferred": "vk-deferred-native"}[path]),
        }
        manifest["Presets"] = {api: preset_ids[api] for api in backend}
        manifest["RendererSettings"] = {"Path": path, "EnableDDGI": False,
                                        "TAAEnabled": True, "RayTracedShadowsEnabled": rt,
                                        "MSAASampleCount": 1, "Upscale": "Off", "UpscaleTechnique": "Spatial"}
        if path in {"Forward", "ForwardPlus"}:
            manifest["Attachments"] = [attachment for attachment in source["Attachments"]
                                       if attachment["Name"] in {"Beauty", "SceneColorHDR", "SceneDepth"}]
        destination = manifests / name
        destination.write_text(yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True), encoding="utf-8", newline="\n")
        print(destination)
        variants = []
        if path == "Deferred" and not rt:
            variants.append(("msaa4", {"MSAASampleCount": 4}))
        variants.append(("upscale-quality", {"Upscale": "Quality", "UpscaleTechnique": "Spatial"}))
        for suffix, settings in variants:
            variant = dict(manifest)
            variant["Id"] = manifest["Id"] + "-" + suffix
            variant["Description"] = (manifest["Description"] + " Diagnostic variation of the named native preset; "
                                      "the settings override is measured separately from production budgets.")
            variant["RendererSettings"] = {**manifest["RendererSettings"], **settings}
            variant_path = manifests / f"{destination.stem}-{suffix}.yaml"
            variant_path.write_text(yaml.safe_dump(variant, sort_keys=False, allow_unicode=True),
                                    encoding="utf-8", newline="\n")
            print(variant_path)


if __name__ == "__main__":
    main()
